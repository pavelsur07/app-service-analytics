// Ozon отдаёт уменьшенную копию, если перед именем файла вставить
// сегмент размера: .../multimedia-1-h/11107018133.jpg превращается
// в .../multimedia-1-h/wc100/11107018133.jpg. Замерено на девяти разных
// шардах: 200, image/webp, 1–2,5 КБ против 224 КБ у оригинала.
//
// wc100, а не wc50: ячейка 32px, и на экране тройной плотности нужно
// до 96 device px. wc250 при таком размере ничего не добавляет, кроме веса.
const THUMBNAIL = 'wc100'

/**
 * Адрес превью для ячейки таблицы.
 *
 * Размер считает фронтенд, а не каталог: в базе лежит ровно то, что
 * прислала площадка, а какого размера нужна картинка — решение вёрстки.
 * Захочется превью крупнее в раскрытой строке — менять здесь, не в базе.
 *
 * Незнакомая форма адреса возвращается как есть, а не калечится: тогда
 * картинка просто грузится оригиналом вместо того, чтобы не грузиться
 * вовсе.
 */
export function thumbnailUrl(url: string | null | undefined): string | null {
  if (url === null || url === undefined || url === '') {
    return null
  }

  // Повторный вызов не должен вставлять сегмент второй раз.
  if (url.includes(`/${THUMBNAIL}/`)) {
    return url
  }

  // Разбор через URL, а не регуляркой по строке: регулярка «последний
  // сегмент» на адресе без пути принимает за имя файла сам хост
  // и выдаёт https:/wc100/example.test. Ничего кроме имени файла
  // не трогаем — ни шард бакета, ни хост из артикула не выводятся
  // и по кускам не собираются, они приходят от площадки как есть.
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    return url
  }

  const at = parsed.pathname.lastIndexOf('/')
  if (at <= 0) {
    return url
  }

  parsed.pathname = `${parsed.pathname.slice(0, at)}/${THUMBNAIL}${parsed.pathname.slice(at)}`

  return parsed.toString()
}
