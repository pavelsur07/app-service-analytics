import { setupServer } from 'msw/node'
import { createOpenApiHttp } from 'openapi-msw'

import type { paths } from '../../src/api/schema'

/**
 * Мок-сервер, отвечающий по схеме OpenAPI (CLAUDE.md §10).
 *
 * До него тесты подменяли глобальный `fetch` и собирали `Response`
 * руками. Так можно успешно проверить ответ, которого контракт вообще
 * не допускает: тест зелёный, а с настоящим бэкендом код падает.
 *
 * `createOpenApiHttp<paths>` типизирован сгенерированной схемой —
 * несуществующий путь и ответ неверной формы не компилируются.
 * Перехват идёт на уровне сети, поэтому код под тестом зовёт настоящий
 * `fetch` и проходит весь свой путь, включая разбор ошибок.
 *
 * baseUrl конкретный, а не '*': клиент приложения ходит относительными
 * путями (`/api/...`), и в Node у них нет базы — `fetch` падает
 * на разборе адреса ещё до перехвата. Поэтому тесты зовут его абсолютным
 * адресом с этой базой.
 *
 * Отсюда предел: проверить, что `createCompanyApiClient` действительно
 * подставляет companyId в путь, так нельзя — он строит относительный
 * путь всегда. Это станет возможно, когда у seller появится DOM-окружение
 * в тестах; пока companyId в пути покрыт e2e и §1 на стороне бэкенда.
 */
export const http = createOpenApiHttp<paths>({ baseUrl: 'http://localhost' })

export const server = setupServer()
