// Адрес карточки Ozon → идентификатор товара.
//
// Форма адреса: /product/<слаг>-<цифры>/ — цифры в хвосте слага
// и есть идентификатор. Слаг меняется при переименовании товара,
// цифры нет, поэтому берём только их.
//
// Проверено на живых карточках 2026-08-14 (вопрос 3 спайка, пакет 0):
// число в хвосте адреса совпадает с `sku` товара, по которому у нас
// записан marketplace_sku. Три размера одного товара — 308403988,
// 308520421, 308866704 — нашлись в каталоге кабинета как есть.
//
// Важная подробность оттуда же: у товара бывает несколько sku, по одному
// на схему доставки (`sources[]` в v3/product/info/list). В адресе
// карточки стоит тот, который отдаёт v3/product/list, — второй (`fbs`)
// в адресах не встретился ни разу. Поэтому каталог синхронизируется
// одним запросом и хранит один sku на товар.
//
// Оговорка: доказательство — карточки одного товарного семейства.
// Если появится своя карточка, на которой панель говорит «продаж нет»
// при заведомо имеющихся продажах, проверять надо здесь: возможно,
// в адресе оказался sku другой схемы доставки.
const PRODUCT_PATH = /^\/product\/(?:.*-)?(\d{6,})\/?$/

export function ozonProductIdFromUrl(rawUrl: string): string | null {
  let url: URL
  try {
    url = new URL(rawUrl)
  } catch {
    return null
  }

  if (!isOzonHost(url.hostname)) {
    return null
  }

  const matched = PRODUCT_PATH.exec(url.pathname)

  return matched?.[1] ?? null
}

function isOzonHost(hostname: string): boolean {
  // www.ozon.ru и ozon.ru — один и тот же сайт; поддомены вроде
  // seller.ozon.ru это кабинет, а не карточка, и сюда попадать
  // не должны.
  return 'ozon.ru' === hostname || 'www.ozon.ru' === hostname
}
