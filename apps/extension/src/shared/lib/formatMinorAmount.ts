// Копейки (минорные единицы) в отображаемую сумму. Панель не считает
// деньги — только форматирует то, что посчитал бэкенд (patterns.md).
//
// Копия apps/seller/src/shared/lib/formatMinorAmount.ts — намеренно
// такая же, вплоть до отсутствия maximumFractionDigits: клиент сверяет
// цифру с отчётом площадки, и округление до рублей в этом сравнении
// выглядит как расхождение. Два потребителя — повод вынести функцию
// в общий пакет; такого пакета сейчас нет, и заводить его ради одной
// функции — решение шире этой задачи. Пока копия с явной ссылкой,
// а расхождение ловится тестами с одинаковыми ожиданиями.
export function formatMinorAmount(
  minorAmount: number,
  currency: string,
): string {
  return new Intl.NumberFormat('ru-RU', { style: 'currency', currency }).format(
    minorAmount / 100,
  )
}
