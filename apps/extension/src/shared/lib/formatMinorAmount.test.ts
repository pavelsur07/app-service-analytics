import { describe, expect, it } from 'vitest'

import { formatMinorAmount } from './formatMinorAmount'

// Обязательное покрытие §10: чистые функции форматирования.
describe('форматирование минорных единиц', () => {
  it('копейки не теряются', () => {
    // Клиент сверяет цифру с отчётом площадки: округление до рублей
    // выглядит там как расхождение и подрывает доверие ко всей панели.
    // Разделитель разрядов у Intl — неразрывный пробел, а не обычный:
    // сверяемся регуляркой, иначе тест ловил бы не форматирование,
    // а конкретный символ пробела в конкретной версии ICU.
    expect(formatMinorAmount(549_437, 'RUB')).toMatch(/5\s?494,37/u)
  })

  it('целая сумма показывается с нулями после запятой', () => {
    expect(formatMinorAmount(549_400, 'RUB')).toMatch(/5\s?494,00/u)
  })

  it('ноль — валидная сумма, а не пустое место', () => {
    expect(formatMinorAmount(0, 'RUB')).toContain('0,00')
  })

  it('валюта берётся из аргумента, а не подразумевается', () => {
    // Умолчания у валюты нет (ADR-004): её всегда сообщает бэкенд.
    expect(formatMinorAmount(100_000, 'USD')).not.toEqual(
      formatMinorAmount(100_000, 'RUB'),
    )
  })
})
