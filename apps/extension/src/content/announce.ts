// Единственная задача — сообщить странице приложения, что расширение
// установлено и какой у него идентификатор.
//
// Зачем вообще: чтобы отправить расширению токен, страница вызывает
// chrome.runtime.sendMessage(<id>, ...) — то есть обязана знать id.
// Он выводится из ключа в манифесте, а пока ключ не выпущен, у каждой
// установки свой. Прописывать id в сборку SPA переменной окружения
// означало бы держать два значения синхронно в двух приложениях
// и в проде, и в dev.
//
// Здесь расширение сообщает id само. Побочно это же и есть определение
// «расширение установлено»: атрибута нет — предлагать подключение
// незачем.
//
// Скрипт вешается только на домен приложения (manifest.config.ts,
// content_scripts.matches) — на страницах маркетплейсов его нет.
document.documentElement.dataset.conwixExtensionId = chrome.runtime.id
