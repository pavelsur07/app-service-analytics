// Ключ кэша системного контура. companyQueryKey из apps/seller сюда
// не подходит и не нужен: раздел Admin управляет сервисом целиком,
// компании в ключе нет (ADR-017).
//
// Хелпер обязателен всё равно: литеральный массив в queryKey линтер
// запрещает синтаксически, независимо от смысла ключа (CLAUDE.md §7).
// Причина та же, что у продавца, — ключ, собранный на месте, однажды
// разойдётся с ключом инвалидации, и экран покажет несвежие данные.
export function adminQueryKey(
  entity: string,
  ...params: readonly unknown[]
): readonly unknown[] {
  return ['admin', entity, ...params]
}
