<?php

declare(strict_types=1);

namespace App\PriceMonitoring\Domain;

use Symfony\Component\Uid\Uuid;

interface TrackedSkuRepository
{
    /**
     * Включает отслеживание: заводит строку либо возвращает в `active`
     * ранее остановленную. Идемпотентно — повторный клик по уже
     * отслеживаемому артикулу не создаёт второй строки и ничего
     * не меняет.
     *
     * Одним запросом с разрешением конфликта по уникальному ключу,
     * а не «поискать и решить»: два параллельных клика прошли бы
     * проверку оба (CLAUDE.md §4).
     */
    public function track(TrackedSku $trackedSku): void;

    /**
     * $companyId первым параметром (CLAUDE.md §1).
     *
     * Останавливает по артикулу, без подключения — и это тот же ключ,
     * которым артикул заводится: продавец отслеживает товар, а не пару
     * «товар в этом кабинете».
     *
     * Возвращает true, если остановил именно этот вызов; false — если
     * активной записи не было (не заводилась или уже остановлена).
     * Условие живёт внутри UPDATE по той же причине, что
     * в `ExtensionTokenRepository::revokeIfActive`.
     */
    public function stopIfActive(string $companyId, string $marketplaceSku, \DateTimeImmutable $at): bool;

    /**
     * Кабинет, к которому привязано активное отслеживание артикула,
     * либо null, если компания его не отслеживает.
     *
     * Один вопрос, а не два: приём наблюдения обязан и проверить право
     * его прислать, и узнать, в какой кабинет строку отнести, — а это
     * ровно одна и та же строка. Разделив, мы читали бы её дважды
     * и могли бы получить разные ответы.
     *
     * $companyId первым параметром (CLAUDE.md §1).
     */
    public function activeAccountIdFor(string $companyId, string $marketplaceSku): ?Uuid;

    /**
     * Сколько **других** артикулов компания отслеживает сейчас. Нужен
     * потолку на список — см. `StartTrackingAction`.
     *
     * Исключение самого артикула — не мелочь, а условие идемпотентности
     * на границе. Считая его вместе со всеми, повторная отправка
     * пятидесятого артикула (например, после сетевого таймаута) упиралась
     * бы в потолок и получала отказ на действие, которое в прошлый раз
     * прошло, — то есть ровно в том случае, ради которого идемпотентность
     * и существует.
     */
    public function countActiveExcluding(string $companyId, string $marketplaceSku): int;
}
