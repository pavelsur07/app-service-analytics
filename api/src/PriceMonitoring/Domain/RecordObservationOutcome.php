<?php

declare(strict_types=1);

namespace App\PriceMonitoring\Domain;

/**
 * Чем закончился приём наблюдения цены (ADR-014).
 */
enum RecordObservationOutcome
{
    case Recorded;

    /**
     * Такой снимок уже записан. Для клиента это успех: расширение
     * повторяет отправку при сетевом сбое, и повтор обязан быть
     * неотличим от первой удачной попытки.
     */
    case Duplicate;

    /**
     * Компания этот артикул не отслеживает. Ожидаемое доменное условие,
     * а не аномалия: между открытием фонового окна и отправкой снимка
     * продавец мог нажать «Остановить».
     *
     * ADR-014 требует записывать это предупреждением, и сегодня оно
     * не записывается: журнала в проекте нет вовсе (monolog ставится
     * отдельным изменением), а Sentry — трекер ошибок, и шум ожидаемых
     * условий сделал бы невидимыми настоящие. Наружу признак идёт кодом
     * ответа. Обещание ADR закрывается вместе с журналом,
     * см. RecordPriceObservationController.
     */
    case NotTracked;
}
