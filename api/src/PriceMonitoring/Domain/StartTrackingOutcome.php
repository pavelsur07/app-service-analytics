<?php

declare(strict_types=1);

namespace App\PriceMonitoring\Domain;

/**
 * Чем закончилась попытка включить отслеживание. Исходы, а не исключения:
 * все три отказа — обычные состояния кабинета продавца, а не поломки.
 *
 * Успех один на все случаи: заведено впервые, возвращено из остановленных
 * и «уже отслеживается» снаружи неразличимы намеренно. Клиенту во всех
 * трёх нужно одно — показать, что артикул под наблюдением.
 */
enum StartTrackingOutcome
{
    case Tracked;

    /**
     * У компании нет активного подключения Ozon: не подключала вовсе,
     * либо подключение в `broken`/`revoked` (ADR-007). Отслеживать
     * нечем — цену снимает расширение, но артикул мы привязываем
     * к кабинету.
     */
    case NoActiveOzonConnection;

    /**
     * Активных Ozon-подключений больше одного. Выбирать за продавца,
     * к какому кабинету привязать артикул, нельзя — и строить выбор
     * в интерфейсе заранее тоже (ADR-014, открытый вопрос №3).
     */
    case MultipleOzonConnections;

    /**
     * Достигнут потолок отслеживаемых артикулов — см. `StartTrackingAction`.
     */
    case LimitReached;
}
