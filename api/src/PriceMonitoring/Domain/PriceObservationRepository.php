<?php

declare(strict_types=1);

namespace App\PriceMonitoring\Domain;

interface PriceObservationRepository
{
    /**
     * Записывает снимок. Возвращает true, если строка появилась именно
     * от этого вызова; false — если такая уже была.
     *
     * Идемпотентность держит уникальный ключ в базе, а не проверка
     * перед вставкой (CLAUDE.md §4): конфликт разрешается внутри самого
     * INSERT. Оба исхода для вызывающего успешны — расширение повторяет
     * отправку при сетевом сбое, и повтор обязан быть неотличим
     * от первой удачной попытки.
     *
     * companyId не отдельным параметром, а внутри самого наблюдения:
     * компанию приносит сюда уже собранная сущность, и разъехаться
     * этим двум значениям негде (CLAUDE.md §1).
     */
    public function record(PriceObservation $observation): bool;
}
