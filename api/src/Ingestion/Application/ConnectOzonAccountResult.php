<?php

declare(strict_types=1);

namespace App\Ingestion\Application;

/**
 * Исходы подключения кабинета, которые контроллер обязан различать
 * по-разному: у каждого свой ответ и своё следующее действие клиента
 * (ADR-021).
 */
enum ConnectOzonAccountResult
{
    case Connected;
    /** Площадка не приняла ключ на области товаров — проверить пару и тип ключа. */
    case Rejected;
    /** Ключ не имеет права читать продажи — включить эту область в кабинете продавца. */
    case RejectedSales;
    /** Ключ не имеет права читать финансовые начисления — включить эту область в кабинете продавца. */
    case RejectedExpenses;
    /** Ключ не имеет права читать возвраты — включить эту область в кабинете продавца. */
    case RejectedReturns;
    /** Кабинет уже подключён к этой или другой компании. */
    case AlreadyConnected;
    /** Площадка не ответила — подождать, а не выпускать новый ключ. */
    case Unavailable;
}
