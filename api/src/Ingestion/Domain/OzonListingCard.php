<?php

declare(strict_types=1);

namespace App\Ingestion\Domain;

/**
 * Что карточка Ozon говорит о себе: наименование и адрес главного фото.
 *
 * Отдельный readonly DTO, а не массив: парсер и обработчик говорят
 * о двух величинах сразу, и массив с ключами по строкам разъезжается
 * при первой же правке (тот же довод, что у OzonListingPrice).
 *
 * Оба поля едут в одну и ту же строку marketplace_listing и меняются
 * вместе — в отличие от цены, у которой своя таблица и своя история.
 * Поэтому здесь один DTO на два поля, а не два разбора одного тела.
 */
final readonly class OzonListingCard
{
    public function __construct(
        public string $name,
        /**
         * Адрес главного фото или null, если его в ответе нет.
         * Вывести адрес из артикула нельзя: медиа-идентификатор в нём
         * не связан ни с sku, ни с offer_id, ни с product_id, а шард
         * бакета (`multimedia-1-h`, `-x`, `-n`, …) меняется от карточки
         * к карточке. Либо храним то, что прислали, либо фото нет.
         */
        public ?string $photoUrl,
    ) {
    }
}
