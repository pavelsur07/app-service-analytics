<?php

declare(strict_types=1);

namespace App\Ingestion\Domain;

/**
 * Чем закончилась попытка задать или исправить себестоимость.
 *
 * Исход, а не исключение: «цена с этой даты уже задана» — не сбой,
 * а осмысленный ответ, на который у экрана есть действие (открыть
 * существующую и исправить). Тот же приём, что у замены учётных данных
 * подключения.
 */
enum ListingCostOutcome
{
    case Saved;

    /**
     * Цена с этой датой начала действия уже существует. Заводить вторую
     * нельзя: тогда на один день пришлись бы две себестоимости, и выбор
     * между ними стал бы делом случая.
     */
    case AlreadySetForThatDate;

    case NotFound;

    /** Позицию изменил кто-то ещё между чтением и записью (ADR-008). */
    case VersionConflict;
}
