<?php

declare(strict_types=1);

namespace App\Identity\Domain;

/**
 * Только добавление. Чтения журнала в интерфейсе нет, пока нет экрана,
 * который бы его показывал; изменения и удаления не будет никогда.
 *
 * Запись не фиксируется сама: она попадает в базу вместе с тем
 * изменением, ради которого сделана. Иначе возможен исход, при котором
 * учётные данные заменены, а следа об этом нет, — то есть ровно
 * невыполненное требование ADR-007 при внешне успешной операции.
 */
interface AuditRecordRepository
{
    /**
     * Ставит запись в очередь на сохранение. Фиксируется вместе
     * с сохранением сущности, которую эта запись описывает.
     */
    public function addToUnitOfWork(AuditRecord $record): void;
}
