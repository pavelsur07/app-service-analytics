<?php

declare(strict_types=1);

namespace App\Identity\Domain;

/**
 * Граница сброса пароля до входа (CLAUDE.md §1, ADR-037). Погашение по
 * предъявленному хэшу межарендаторное по построению: пользователя
 * определяет найденный токен. Поиска по произвольному userId и списка
 * токенов этот контракт не предоставляет.
 */
interface PasswordResetTokenRepository
{
    /**
     * Выпускает ссылку и той же транзакцией гасит все прежние непогашенные
     * ссылки пользователя: действует только последнее письмо.
     */
    public function issue(PasswordResetToken $token): void;

    /**
     * Атомарно погашает ссылку, меняет хэш пароля, гасит остальные ссылки
     * пользователя и пишет аудит. Возвращает адрес пользователя для
     * письма-уведомления; null — ссылка неизвестна, истекла или уже
     * использована (наружу эти исходы неразличимы).
     */
    public function resetPassword(string $tokenHash, string $passwordHash, \DateTimeImmutable $now): ?string;
}
