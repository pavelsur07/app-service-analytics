<?php

declare(strict_types=1);

namespace App\Identity\Domain;

/**
 * В Domain, а не рядом со сценарием: тип возвращается наружу через Facade,
 * и Ingestion обязан его видеть, не получая доступа к Application-слою
 * Identity целиком. Сами исходы предметные, а не технические: отзыв
 * необратим (ADR-011), конфликт версий — правило ADR-008.
 *
 * Исходы замены учётных данных, которые вызывающая сторона обязана
 * различать: каждому соответствует свой ответ клиенту и своё действие
 * с его стороны.
 */
enum ReplaceCredentialsOutcome
{
    case Replaced;
    case NotFound;
    /** Отзыв необратим (ADR-011) — заменой ключа подключение не оживить. */
    case Revoked;
    /** Данные изменил кто-то ещё (ADR-008) — перечитать и повторить. */
    case VersionConflict;
}
