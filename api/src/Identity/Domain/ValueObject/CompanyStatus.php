<?php

declare(strict_types=1);

namespace App\Identity\Domain\ValueObject;

/**
 * Состояние клиентского аккаунта (ADR-017). Заблокированный аккаунт
 * не удаляется и не помечается неполным задним числом — он просто
 * перестаёт пускать своих пользователей со следующего запроса.
 *
 * Переход обратим, поэтому по признаку ADR-011 каждый пишется
 * в аудит-журнал: без него на вопрос «кто и когда выключил этот
 * аккаунт» ответа не существует вовсе.
 */
enum CompanyStatus: string
{
    case Active = 'active';
    case Blocked = 'blocked';
}
